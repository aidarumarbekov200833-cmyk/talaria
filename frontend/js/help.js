let query = '';

function matches(article) {
  if (!query) return true;
  const haystack = `${article.title} ${article.tags} ${article.steps.join(' ')} ${
    article.note || ''
  }`.toLowerCase();
  return query
    .toLowerCase()
    .split(/\s+/)
    .filter(Boolean)
    .every((word) => haystack.includes(word));
}

function articleNode(article) {
  const box = document.createElement('details');
  box.className = 'help-item';
  box.dataset.helpId = article.id;
  const head = document.createElement('summary');
  head.textContent = article.title;
  box.append(head);

  const list = document.createElement('ol');
  list.className = 'help-steps';
  article.steps.forEach((step) => {
    const item = document.createElement('li');
    item.textContent = step;
    list.append(item);
  });
  box.append(list);

  if (article.note) {
    const note = document.createElement('p');
    note.className = 'help-note';
    note.textContent = article.note;
    box.append(note);
  }
  if (article.section) {
    const open = document.createElement('button');
    open.type = 'button';
    open.className = 'btn ghost help-open';
    open.textContent = 'Открыть раздел';
    open.addEventListener('click', () => goTo(article.section));
    box.append(open);
  }
  return box;
}

function render() {
  const list = document.getElementById('helpList');
  if (!list) return;
  list.textContent = '';
  const found = ARTICLES.filter(matches);
  if (!found.length) {
    const empty = document.createElement('div');
    empty.className = 'dd-empty';
    empty.textContent = 'Ничего не нашлось. Напишите в поддержку — отвечу лично.';
    list.append(empty);
    return;
  }
  found.forEach((article) => list.append(articleNode(article)));
  // Единственная найденная статья раскрывается сразу: искали именно её.
  if (found.length === 1) list.firstElementChild.open = true;
}

/** Поиск по справке. Зовётся из разметки при вводе. */
export function filterHelp() {
  query = (document.getElementById('helpSearch')?.value || '').trim();
  render();
}

/**
 * Открыть центр помощи.
 *
 * `topic` — id статьи или имя раздела кабинета: тогда нужная статья раскрыта
 * сразу. Так кнопка «Помощь» из раздела попадает в его собственную главу, а не
 * в оглавление.
 */
export function openHelpCenter(topic = '') {
  const field = document.getElementById('helpSearch');
  if (field) field.value = '';
  query = '';
  render();
  closeAccountMenu();
  // Отдельная страница вместо модалки (v43): статьи длинные.
  goTo('help');
  const wanted = String(topic || '');
  const article =
    ARTICLES.find((item) => item.id === wanted) || ARTICLES.find((item) => item.section === wanted);
  if (article) {
    const node = document.querySelector(`[data-help-id="${article.id}"]`);
    if (node) {
      node.open = true;
      node.scrollIntoView({ block: 'nearest' });
    }
  }
  setTimeout(() => field?.focus(), 160);
}

/** Кнопка «Написать в поддержку» из справки. */
export function helpToSupport() {
  openSupport();
}

/** Открыть справку по разделу, который открыт сейчас. */
export function openHelpForCurrentSection() {
  const active = document.querySelector('.section.active')?.id || '';
  openHelpCenter(active);
}

// Оглавление рисуется сразу при загрузке модуля: на страницу помощи можно
// попасть не только через openHelpCenter, но и по F5 (nav.js возвращает в
// сохранённый раздел напрямую через goTo) — без этого она была бы пустой.
render();
