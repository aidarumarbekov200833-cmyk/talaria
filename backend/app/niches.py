KEYWORDS_NOTE = (
    "Ключевые слова собраны перебором: тематика ниши плюс уточнения "
    "(«для начинающих», «обзор», «с нуля» и т. п.). Это не генерация ИИ и не "
    "данные YouTube — просто заготовки для поиска, их можно править вручную."
)


def build_keywords(seeds: list[str], count: int) -> list[str]:
    """Собрать `count` уникальных ключевых слов из набора основ.

    Идём по модификаторам внешним циклом, чтобы сначала получить по одному
    короткому запросу на каждую основу, а уже потом — уточнения. Иначе при
    count=5 и трёх нишах все пять слов достались бы первой нише.
    """
    seeds = [s.strip() for s in seeds if s and s.strip()]
    if not seeds or count <= 0:
        return []

    out: list[str] = []
    seen: set[str] = set()
    for modifier in MODIFIERS:
        for seed in seeds:
            phrase = f"{seed} {modifier}".strip() if modifier else seed
            low = phrase.lower()
            if low in seen:
                continue
            seen.add(low)
            out.append(phrase)
            if len(out) >= count:
                return out
    return out


def seeds_for(slugs: list[str]) -> list[str]:
    """Основы для выбранных ниш, по одной ниши за раз (чередуя)."""
    picked = [NICHE_BY_SLUG[s] for s in slugs if s in NICHE_BY_SLUG]
    if not picked:
        return []
    out: list[str] = []
    depth = max(len(n["seeds"]) for n in picked)
    for i in range(depth):
        for niche in picked:
            if i < len(niche["seeds"]):
                out.append(niche["seeds"][i])
    return out
